import type { NextConfig } from "next";

const isDev = process.env.NODE_ENV !== "production";

/**
 * Clerk and Cloudflare left this list along with the dependency, so the policy
 * is now `self` and nothing else. `unsafe-eval` is granted only in development,
 * where the bundler's runtime needs it.
 */
const csp = [
  "default-src 'self'",
  isDev
    ? "script-src 'self' 'unsafe-inline' 'unsafe-eval'"
    : "script-src 'self' 'unsafe-inline'",
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data: blob:",
  "font-src 'self'",
  "connect-src 'self'",
  "frame-src 'none'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
].join("; ");

const nextConfig: NextConfig = {
  /**
   * The SQLite path applies migrations at runtime from `db/migrations`, which is
   * source rather than an import, so the tracer would otherwise leave it out of
   * the deployment and the schema would never be created.
   */
  outputFileTracingIncludes: {
    "/**": ["./db/migrations/**"],
  },
  async headers() {
    return [
      {
        source: "/(.*)",
        headers: [
          { key: "Content-Security-Policy", value: csp },
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "X-Frame-Options", value: "SAMEORIGIN" },
          { key: "X-XSS-Protection", value: "0" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
          {
            key: "Permissions-Policy",
            value: "camera=(), microphone=(), geolocation=()",
          },
          {
            key: "Strict-Transport-Security",
            value: "max-age=63072000",
          },
        ],
      },
    ];
  },
};

export default nextConfig;
